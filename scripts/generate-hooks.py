from pathlib import Path
import sys

root=Path(__file__).resolve().parent.parent
check='--check' in sys.argv
for name in ('r3s-monitor','usb-fan-control'):
    install=(root/name/'install.sh').read_text(encoding='utf-8')
    # Derive the read-only preflight from the existing installer, ending before
    # its first backup/file/service mutation. Keep the hardware gates identical.
    prefix=install.split('mkdir -p "$BACKUP/root"',1)[0].split('\n',1)[1]
    hooks={
        'preinst':'#!/bin/sh\n[ -n "${IPKG_INSTROOT:-}" ] && exit 0\nR3S_PACKAGE_MODE=1\n'+prefix+'\nexit 0\n',
        'postinst':f'#!/bin/sh\n[ -n "${{IPKG_INSTROOT:-}}" ] && exit 0\nR3S_PACKAGE_MODE=1 /usr/libexec/{name}-package-install\n',
        'prerm':f'''#!/bin/sh
[ -n "${{IPKG_INSTROOT:-}}" ] && exit 0
if [ "${{PKG_UPGRADE:-0}}" = "1" ] || [ "$1" = "upgrade" ]; then
    exit 0
fi
R3S_PACKAGE_MODE=1 /usr/libexec/{name}-package-uninstall
'''
    }
    content='# Generated by scripts/generate-hooks.py; edit the original installers.\n\n'
    for event,body in hooks.items():
        content+=f'define Package/{name}/{event}\n'+body.replace('$','$$')+'endef\n\n'
    p=root/name/'package-hooks.mk'
    if check:
        if p.read_text(encoding='utf-8')!=content: raise SystemExit(f'Stale package hooks: {name}')
    else: p.write_text(content,encoding='utf-8',newline='\n')
print('Package hardware/lifecycle hooks are current.')
